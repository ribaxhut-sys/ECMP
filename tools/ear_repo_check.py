def write_adr_index(root: Path, adrs):
    out = root / "05 Architecture Decision Records" / "ADR_INDEX.generated.md"
    lines = [
        "# ADR Index (Generated)",
        "",
        "| Field | Value |",
        "|---|---|",
        "| ID | ADR-IDX-001 |",
        "| Version | 0.1 |",
        "| Owner | Automation |",
        "| Reviewer | Solution Architect |",
        "| Approver | Architecture Board |",
        "| Status | 🟡 Draft |",
        "| Last Review | auto |",
        "| Next Review | auto |",
        "",
        "> Generated by `tools/ear_repo_check.py`. Create real ADRs with ID `ADR-NNN`.",
        "",
        "| ADR | Title/File | Status | Owner | Last Review | Path |",
        "|---|---|---|---|---|---|",
    ]
    if not adrs:
        lines.append("| — | No ADR records yet | — | — | — | — |")
    else:
        for row in adrs:
            lines.append(
                f"| {row['id']} | {row['title']} | {row['status']} | {row['owner']} | {row['last_review']} | `{row['path']}` |"
            )
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


def main():
    parser = argparse.ArgumentParser(description="ECMP EAR self-governance checker")
    parser.add_argument("--root", default=str(ROOT))
    parser.add_argument("--write-inventory", action="store_true")
    parser.add_argument("--write-health", action="store_true")
    parser.add_argument("--write-adr-index", action="store_true")
    parser.add_argument("--write-all", action="store_true", help="Write inventory + health + ADR index")
    parser.add_argument("--strict", action="store_true", help="Fail on missing/incomplete metadata")
    parser.add_argument("--fail-on-review-due", action="store_true")
    args = parser.parse_args()

    root = Path(args.root).resolve()
    today = date.today()

    missing_metadata = []
    incomplete_metadata = []
    missing_owner = []
    review_due = []
    broken_links = []
    total_md = 0

    for path in iter_markdown_files(root):
        total_md += 1
        text = path.read_text(encoding="utf-8", errors="ignore")
        rel = path.relative_to(root).as_posix()
        meta = parse_metadata(text)

        if not meta.get("ID") or not meta.get("Status") or not meta.get("Owner"):
            missing_metadata.append(rel)
        else:
            missing_fields = [f for f in META_FIELDS if f not in meta or not meta[f]]
            if missing_fields:
                incomplete_metadata.append(f"{rel} ({', '.join(missing_fields)})")
            if not meta.get("Owner"):
                missing_owner.append(rel)
            next_review = parse_date(meta.get("Next Review", ""))
            if next_review and next_review < today:
                review_due.append(f"{rel} (Next Review {next_review.isoformat()})")

        for link in check_links(path, text):
            broken_links.append(f"{rel} -> {link}")

    inventory = build_inventory(root)
    missing_readme = sum(1 for _, _, has in inventory if not has)
    adrs = collect_adrs(root)
    _, unused_templates = template_usage(root)

    stats = {
        "total_md": total_md,
        "folders": len(inventory),
        "missing_metadata": len(missing_metadata),
        "incomplete_metadata": len(incomplete_metadata),
        "broken_links": len(broken_links),
        "review_due": len(review_due),
        "missing_owner": len(missing_owner),
        "missing_readme": missing_readme,
    }
    stats["health"] = score_health(stats)

    print("ECMP EAR Repository Health Check")
    print(f"Root: {root}")
    print(f"Repository Health: {stats['health']}%")
    print(f"Markdown files: {total_md}")
    print(f"Missing Metadata: {stats['missing_metadata']}")
    print(f"Incomplete Metadata: {stats['incomplete_metadata']}")
    print(f"Broken Links: {stats['broken_links']}")
    print(f"Review Due: {stats['review_due']}")
    print(f"Missing Owner: {stats['missing_owner']}")
    print(f"Missing README: {stats['missing_readme']}")
    print(f"ADR records: {len(adrs)}")
    print(f"Unused templates (heuristic): {len(unused_templates)}")

    missing_details = {
        "metadata": missing_metadata,
        "incomplete": incomplete_metadata,
        "broken": broken_links,
        "review_due": review_due,
    }

    if args.write_all or args.write_inventory:
        path = write_inventory(root, inventory, stats)
        print(f"Wrote {path}")
    if args.write_all or args.write_health:
        path = write_health_report(root, stats, inventory, missing_details, adrs, unused_templates)
        print(f"Wrote {path}")
    if args.write_all or args.write_adr_index:
        path = write_adr_index(root, adrs)
        print(f"Wrote {path}")

    fail = False
    if broken_links:
        fail = True
    if args.strict and (missing_metadata or incomplete_metadata or missing_readme):
        fail = True
    if args.fail_on_review_due and review_due:
        fail = True
    if fail:
        raise SystemExit(2)


if __name__ == "__main__":
    main()
