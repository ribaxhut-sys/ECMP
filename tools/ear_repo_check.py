#!/usr/bin/env python3
"""ECMP EAR self-governance checker: health, metadata, links, ADR index, inventory."""

from __future__ import annotations

import argparse
import re
from datetime import date, datetime
from pathlib import Path

from repo_check_lib import (
    META_FIELDS,
    build_inventory,
    check_links,
    iter_markdown_files,
    parse_metadata,
    score_health,
)

ROOT = Path(__file__).resolve().parents[1]


def parse_date(value: str):
    value = (value or "").strip()
    if not value or value.lower() in {"auto", "tbd", "yyyy-mm-dd"}:
        return None
    for fmt in ("%Y-%m-%d", "%Y/%m/%d"):
        try:
            return datetime.strptime(value, fmt).date()
        except ValueError:
            continue
    return None


def collect_adrs(root: Path):
    adr_dir = root / "05 Architecture Decision Records"
    rows = []
    if not adr_dir.exists():
        return rows
    for path in sorted(adr_dir.glob("*.md")):
        if path.name.upper().startswith("ADR-TEMPLATE") or path.name == "README.md":
            continue
        if "template" in path.name.lower() or path.name.endswith(".generated.md"):
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        meta = parse_metadata(text)
        adr_id = meta.get("ID", "")
        if not re.match(r"^ADR-\d{3,}$", adr_id, flags=re.IGNORECASE):
            continue
        # Ignore placeholder folder IDs like ADR-000
        if adr_id.upper() in {"ADR-000"}:
            continue
        rows.append(
            {
                "id": adr_id,
                "title": path.stem,
                "status": meta.get("Status", "n/a"),
                "owner": meta.get("Owner", "n/a"),
                "last_review": meta.get("Last Review", "n/a"),
                "path": path.relative_to(root).as_posix(),
            }
        )
    return rows


def template_usage(root: Path):
    templates_dir = root / "24 Templates"
    if not templates_dir.exists():
        return [], []
    templates = [p for p in templates_dir.glob("*") if p.is_file() and p.suffix in {".md", ".yaml", ".yml"}]
    unused = []
    used = []
    corpus = []
    for path in iter_markdown_files(root):
        if "24 Templates" in path.parts:
            continue
        corpus.append(path.read_text(encoding="utf-8", errors="ignore"))
    blob = "\n".join(corpus)
    for tpl in templates:
        token = tpl.name
        stem = tpl.stem
        if token in blob or stem in blob or f"Templates/{token}" in blob or f"Templates\\{token}" in blob:
            used.append(tpl.name)
        else:
            # document header template is referenced by standard name variations
            if stem in {"DOCUMENT_HEADER_TEMPLATE", "ADR_TEMPLATE", "FRD_TEMPLATE"}:
                used.append(tpl.name)
            else:
                unused.append(tpl.name)
    return used, unused


def write_health_report(root: Path, stats: dict, inventory, missing_details, adrs, unused_templates):
    out = root / "00 Repository Guide" / "REPO_HEALTH_REPORT.md"
    today = date.today().isoformat()
    lines = [
        "# Repository Health Report",
        "",
        "| Field | Value |",
        "|---|---|",
        "| ID | EAR-IDX-005 |",
        "| Version | 0.1 |",
        "| Owner | Automation |",
        "| Reviewer | PMO / Enterprise Architecture |",
        "| Approver | Architecture Board |",
        "| Status | 🟡 Draft |",
        f"| Last Review | {today} |",
        "| Next Review | auto |",
        "",
        "> Generated by `tools/ear_repo_check.py`. Do not edit manually.",
        "",
        "## Repository Health",
        "",
        f"**{stats['health']}%**",
        "",
        "| Metric | Count |",
        "|---|---|",
        f"| Markdown files | {stats['total_md']} |",
        f"| Missing Metadata | {stats['missing_metadata']} |",
        f"| Incomplete Metadata | {stats['incomplete_metadata']} |",
        f"| Broken Links | {stats['broken_links']} |",
        f"| Review Due | {stats['review_due']} |",
        f"| Missing Owner | {stats['missing_owner']} |",
        f"| Missing README (numbered folders) | {stats['missing_readme']} |",
        f"| Unused Templates (heuristic) | {len(unused_templates)} |",
        f"| ADR records found | {len(adrs)} |",
        "",
        "## Inventory",
        "",
        "| Folder | Markdown Files | README |",
        "|---|---|---|",
    ]
    for name, count, has_readme in inventory:
        lines.append(f"| {name} | {count} | {'✅' if has_readme else '❌'} |")

    if missing_details["metadata"]:
        lines += ["", "## Missing Metadata", ""]
        lines += [f"- {x}" for x in missing_details["metadata"][:40]]
    if missing_details["incomplete"]:
        lines += ["", "## Incomplete Metadata Fields", ""]
        lines += [f"- {x}" for x in missing_details["incomplete"][:40]]
    if missing_details["broken"]:
        lines += ["", "## Broken Links", ""]
        lines += [f"- {x}" for x in missing_details["broken"][:40]]
    if missing_details["review_due"]:
        lines += ["", "## Review Due", ""]
        lines += [f"- {x}" for x in missing_details["review_due"][:40]]
    if unused_templates:
        lines += ["", "## Unused Templates (heuristic)", ""]
        lines += [f"- {x}" for x in unused_templates]

    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


