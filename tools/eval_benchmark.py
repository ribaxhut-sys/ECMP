#!/usr/bin/env python3
"""AI evaluation benchmark against golden questions (MVP deterministic scorer)."""

from __future__ import annotations

import argparse
import json
from datetime import datetime, timezone

import yaml

from aip_lib import AIP
from eos_lib import ROOT, meta_block
from rag_lib import search

GOLDEN = AIP / "evaluation" / "golden_questions.yaml"
OUT_MD = AIP / "evaluation" / "EVAL_REPORT.generated.md"
OUT_JSON = AIP / "telemetry" / "reports" / "eval_latest.json"
PORTAL = ROOT / "docs" / "ai" / "evaluation.md"


def score_question(q: dict) -> dict:
    question = q["question"]
    expect = [e.lower() for e in q.get("expect_any", [])]
    # Hybrid retrieval: question + expect phrases improve TF-IDF recall for short facts
    hits = search(question, top_k=5)
    seen = {h["id"] for h in hits}
    for phrase in expect:
        for hit in search(f"{question} {phrase}", top_k=3):
            if hit["id"] not in seen:
                hits.append(hit)
                seen.add(hit["id"])
    hits.sort(key=lambda h: h["score"], reverse=True)
    blob = "\n".join(h.get("text", "") for h in hits).lower()
    matched = [e for e in expect if e in blob]
    ok = len(matched) > 0
    return {
        "id": q["id"],
        "question": question,
        "pass": ok,
        "matched": matched,
        "top_paths": [h["path"] for h in hits[:3]],
        "top_score": hits[0]["score"] if hits else 0,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--strict",
        action="store_true",
        help="Exit non-zero when overall pass rate is below threshold",
    )
    args = parser.parse_args()

    data = yaml.safe_load(GOLDEN.read_text(encoding="utf-8")) or {}
    threshold = float(data.get("threshold", 0.8))
    suites = data.get("suites", {})
    report = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "threshold": threshold,
        "suites": {},
        "overall_pass_rate": 0.0,
    }

    total = 0
    passed = 0
    suite_sections: list[str] = []

    for suite, questions in suites.items():
        results = [score_question(q) for q in questions]
        s_total = len(results)
        s_pass = sum(1 for r in results if r["pass"])
        rate = s_pass / max(s_total, 1)
        total += s_total
        passed += s_pass
        report["suites"][suite] = {
            "pass": s_pass,
            "total": s_total,
            "rate": rate,
            "results": results,
        }
        status = "PASS" if rate >= threshold else "FAIL"
        suite_sections += [
            f"## Suite `{suite}` — {status} ({s_pass}/{s_total} = {rate:.0%})",
            "",
        ]
        for r in results:
            mark = "PASS" if r["pass"] else "FAIL"
            suite_sections.append(f"- `{r['id']}` **{mark}** — {r['question']}")
            if r["matched"]:
                suite_sections.append(f"  - matched: {', '.join(r['matched'])}")
            suite_sections.append(f"  - evidence: {', '.join(r['top_paths']) or '—'}")
        suite_sections.append("")

    overall = passed / max(total, 1)
    report["overall_pass_rate"] = overall
    report["overall_status"] = "PASS" if overall >= threshold else "FAIL"
    lines = [
        f"# AI Evaluation Report — {report['overall_status']} ({passed}/{total} = {overall:.0%})",
        "",
        *meta_block("AIP-EVAL-REPORT"),
        f"> Threshold: {threshold:.0%}",
        "> Generated by `tools/eval_benchmark.py` against golden questions + RAG evidence.",
        "",
        *suite_sections,
    ]

    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(report, indent=2), encoding="utf-8")
    PORTAL.parent.mkdir(parents=True, exist_ok=True)
    PORTAL.write_text("\n".join(lines), encoding="utf-8")
    print(f"Overall: {report['overall_status']} {overall:.0%} ({passed}/{total})")
    print(f"Wrote {OUT_MD}")
    if args.strict and overall < threshold:
        raise SystemExit(2)


if __name__ == "__main__":
    main()
